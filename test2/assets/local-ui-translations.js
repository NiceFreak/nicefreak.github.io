export const RESULT_TERM_TRANSLATIONS = Object.freeze({
  원칙: "原则",
  결과: "结果",
  구조: "结构",
  능력: "能力",
  의미: "意义",
  실리: "实际利益",
});

export function translateResultType(value) {
  const terms = value.split("·");
  if (
    terms.length !== 3 ||
    terms.some((term) => !RESULT_TERM_TRANSLATIONS[term])
  )
    return null;
  return terms.map((term) => RESULT_TERM_TRANSLATIONS[term]).join("·");
}

export function translateAxisId(value) {
  const terms = value.split("-");
  if (
    terms.length !== 2 ||
    terms.some((term) => !RESULT_TERM_TRANSLATIONS[term])
  )
    return null;
  return terms.map((term) => RESULT_TERM_TRANSLATIONS[term]).join("—");
}
